-- Schema da API cobaia. Executado pelo Spring Boot antes do Hibernate, que só o valida
-- (spring.jpa.hibernate.ddl-auto=validate).
--
-- Faixa de IDs: o banco gera IDs a partir de 1000. As fixtures de teste usam IDs fixos de 1 a 999,
-- para nunca colidir com IDs gerados.
--
-- Textos sem tamanho máximo (VARCHAR sem limite no H2): a especificação não define tamanhos, e um
-- limite aqui viraria erro 500 com texto longo.

CREATE TABLE produto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    sku            VARCHAR        NOT NULL UNIQUE,
    nome           VARCHAR        NOT NULL,
    descricao      VARCHAR,
    preco          NUMERIC(12, 2) NOT NULL,
    categoria      VARCHAR        NOT NULL,
    ativo          BOOLEAN        NOT NULL,
    estoque        INTEGER        NOT NULL,
    peso_gramas    INTEGER        NOT NULL,
    altura_cm      INTEGER        NOT NULL,
    largura_cm     INTEGER        NOT NULL,
    comprimento_cm INTEGER        NOT NULL
);

-- Tags de cada produto; "posicao" (a partir de 0) guarda a ordem em que foram enviadas.
CREATE TABLE produto_tag (
    produto_id BIGINT  NOT NULL REFERENCES produto (id),
    posicao    INTEGER NOT NULL,
    tag        VARCHAR NOT NULL,
    PRIMARY KEY (produto_id, posicao)
);

CREATE TABLE carrinho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY
);

-- Itens na ordem de inclusão = ordem crescente de id.
CREATE TABLE item_carrinho (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    carrinho_id BIGINT  NOT NULL REFERENCES carrinho (id),
    produto_id  BIGINT  NOT NULL REFERENCES produto (id),
    quantidade  INTEGER NOT NULL
);

CREATE TABLE pedido (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    status              VARCHAR        NOT NULL,
    cliente_nome        VARCHAR        NOT NULL,
    cliente_email       VARCHAR        NOT NULL,
    endereco_logradouro VARCHAR        NOT NULL,
    endereco_numero     VARCHAR        NOT NULL,
    endereco_complemento VARCHAR,
    endereco_cidade     VARCHAR        NOT NULL,
    endereco_uf         VARCHAR        NOT NULL,
    endereco_cep        VARCHAR        NOT NULL,
    modalidade_frete    VARCHAR        NOT NULL,
    subtotal            NUMERIC(12, 2) NOT NULL,
    desconto            NUMERIC(12, 2) NOT NULL,
    frete               NUMERIC(12, 2) NOT NULL,
    total               NUMERIC(12, 2) NOT NULL
);

-- Itens na ordem de inclusão = ordem crescente de id. Nome e preço congelados na criação do pedido.
CREATE TABLE item_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    pedido_id      BIGINT         NOT NULL REFERENCES pedido (id),
    produto_id     BIGINT         NOT NULL REFERENCES produto (id),
    nome_produto   VARCHAR        NOT NULL,
    quantidade     INTEGER        NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL,
    subtotal       NUMERIC(12, 2) NOT NULL
);
